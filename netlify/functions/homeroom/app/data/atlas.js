/**
 * The Global Biolab Atlas — community biotech, DIYbio and open-science labs
 * worldwide, with an activity status for each.
 *
 * Same premise as the standalone atlas: a directory is only useful if it says
 * which labs are actually open. Half of every DIYbio list on the internet is
 * dead links to spaces that closed in 2017, and a founder who flies somewhere
 * on the strength of one has lost a week.
 *
 * So `status` is a first-class field:
 *   active   — open, running, taking members
 *   limited  — open but reduced: appointment only, project-based, or in transit
 *   dormant  — the organisation exists, the space does not currently
 *   unknown  — listed by a source we trust, not confirmed by us
 *
 * Sources are the same ones the atlas draws on: HTGAA global nodes, the
 * DIYbio.org labs list, the DIYbiosphere repository, and member submissions —
 * which is why `source` is recorded per row. Members can submit corrections,
 * and a correction from someone who has stood in the room outranks any list.
 */

